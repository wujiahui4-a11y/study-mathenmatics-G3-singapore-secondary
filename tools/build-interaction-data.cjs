/* Stable interaction groups from the same Studio snapshot as JJS_DATA. */
const fs = require('node:fs'), zlib = require('node:zlib'), path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = JSON.parse(zlib.gunzipSync(fs.readFileSync(path.join(root, 'jujutsu/jjs/source.json.gz'))));
const parts = source.parts.filter(p => !p.path.startsWith('Workspace.Map.Data.'));
const origin = [0, 20.309, 0], round = n => Math.round(n * 1000) / 1000;
function groups(term) {
  const list = [];
  parts.forEach((p, id) => {
    if (!p.path.includes(term)) return;
    const min = [], max = [];
    for (let a = 0; a < 3; a++) {
      const e = p.size.reduce((s, n, k) => s + Math.abs(p.cf[3 + a * 3 + k]) * n / 2, 0);
      min[a] = p.cf[a] - origin[a] - e; max[a] = p.cf[a] - origin[a] + e;
    }
    list.push({ids: [id], min, max});
  });
  // Merge touching parts, repeating after unions so export order is irrelevant.
  let changed = true;
  while (changed) {
    changed = false;
    for (let i = 0; i < list.length; i++) for (let j = i + 1; j < list.length; j++) {
      const a = list[i], b = list[j];
      if (![0, 1, 2].every(k => a.min[k] <= b.max[k] + .65 && b.min[k] <= a.max[k] + .65)) continue;
      a.ids.push(...b.ids); for (let k = 0; k < 3; k++) {a.min[k] = Math.min(a.min[k], b.min[k]); a.max[k] = Math.max(a.max[k], b.max[k]);}
      list.splice(j--, 1); changed = true;
    }
  }
  return list.map(g => {
    g.ids.sort((a, b) => a - b); g.min = g.min.map(round); g.max = g.max.map(round);
    g.p = g.min.map((v, i) => round((v + g.max[i]) / 2));
    return g;
  }).sort((a, b) => a.ids[0] - b.ids[0]);
}
const ladders = groups('.Ladder.'), bins = groups('.Throwable.Trash.');
for (const g of ladders) {
  const p = parts[g.ids[0]], n = [p.cf[5], 0, p.cf[11]];
  const length = Math.hypot(n[0], n[2]);
  g.n = n.map(x => round(x / (length || 1)));
}
const screens = parts.map((p, id) => ({p, id})).filter(x => x.p.path.endsWith('.RealAd.Screen')).map(({p, id}) => {
  const control = parts.map((q, i) => ({q, i})).filter(x => x.q.path.endsWith('.RealAd.Control'))
    .sort((a, b) => Math.hypot(...a.q.cf.slice(0, 3).map((n, k) => n - p.cf[k])) - Math.hypot(...b.q.cf.slice(0, 3).map((n, k) => n - p.cf[k])))[0];
  return {part: id, control: control.i};
});
fs.writeFileSync(path.join(root, 'jujutsu/interaction-data.js'), '/* Generated by tools/build-interaction-data.cjs. */\nwindow.JJINTERACTION_DATA = ' + JSON.stringify({ladders, bins, screens}) + ';\n');
